export type StringKey = keyof typeof en

type Dict = Record<StringKey, string>

// English is always bundled; Hindi/Bengali are separate chunks
// (strings.hi.ts / strings.bn.ts) so English-only visitors never download
// them. main.tsx loads the saved language before first render (no flash);
// any later switch loads on demand and re-renders via onLangLoaded.
const strings: { en: Dict } & Partial<Record<Lang, Dict>> = { en }
const loaders: Record<Exclude<Lang, 'en'>, () => Promise<{ default: Dict }>> = {
  hi: () => import('./strings.hi'),
  bn: () => import('./strings.bn'),
}
const listeners = new Set<() => void>()
let version = 0

export async function loadLang(lang: Lang): Promise<void> {
  if (lang === 'en' || strings[lang]) return
  strings[lang] = (await loaders[lang]()).default
  version++
  listeners.forEach(fn => fn())
}
export const onLangLoaded = (fn: () => void) => { listeners.add(fn); return () => { listeners.delete(fn) } }
export const langVersion = () => version
export const isLangLoaded = (lang: Lang) => !!strings[lang]

// Missing (not yet loaded) dictionaries fall back to English per key.
export function translate(lang: Lang, key: StringKey, vars?: Record<string, string>): string {
  let out = strings[lang]?.[key] ?? strings.en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, v)
  return out
}

export default strings

